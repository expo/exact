import { cpSync, existsSync, readFileSync, readdirSync, renameSync, rmSync, rmdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

// Makes the tree Cloudflare Pages serves from the one `bun run build` writes: bun tools/pages.ts [dist] [dist.pages].
// Pages answers /start from start/index.html with a redirect to /start/, and _redirects sends /start/ back to
// /start, so a page loops (wrangler 3.114.17). It answers /start from start.html directly, and still redirects
// /start/ and /start.html to /start. Pages also reads at most 100 _headers rules
// (developers.cloudflare.com/pages/platform/limits), fewer than the rule for each page that postbuild.ts writes.
// Those rules give a page text/html, which a .html file has without one.

const SITE = resolve(import.meta.dir, '..');
const DIST = resolve(SITE, process.argv[2] ?? 'dist');
const OUT = resolve(SITE, process.argv[3] ?? 'dist.pages');
const HEADER_RULES = 100;

type Page = { path: string };
const pages: Page[] = JSON.parse(readFileSync(join(SITE, 'content/pages.json'), 'utf8'));
if (!existsSync(join(DIST, '_headers'))) throw new Error(`${DIST} has no _headers: run bun run build first`);
if (!OUT.startsWith(`${SITE}/`)) throw new Error(`${OUT} is outside ${SITE}`);

rmSync(OUT, { recursive: true, force: true });
cpSync(DIST, OUT, { recursive: true });

let moved = 0;
for (const file of readdirSync(OUT, { recursive: true, encoding: 'utf8' }).map(f => f.split('\\').join('/'))) {
  // The installation pages under .exact/ are reached with the trailing slash that Pages gives them.
  if (!file.endsWith('/index.html') || file.startsWith('.exact/')) continue;
  const dir = dirname(file);
  if (existsSync(join(OUT, `${dir}.html`))) throw new Error(`${dir}.html and ${file} would be one file`);
  renameSync(join(OUT, file), join(OUT, `${dir}.html`));
  try { rmdirSync(join(OUT, dir)); } catch { /* it holds the pages below this one */ }
  moved++;
}

const paths = new Set(pages.map(p => p.path));
const rules: string[][] = [];
for (const line of readFileSync(join(OUT, '_headers'), 'utf8').split('\n')) {
  if (!line.trim() || line.startsWith('#')) continue;
  if (/^\s/.test(line)) rules.at(-1)?.push(line);
  else rules.push([line]);
}
const kept = rules.filter(([pattern]) => !paths.has(pattern));
if (kept.length > HEADER_RULES) throw new Error(`_headers has ${kept.length} rules and Pages reads ${HEADER_RULES}`);
writeFileSync(join(OUT, '_headers'), `# Generated by tools/pages.ts from the build's _headers. Do not edit.\n${kept.flat().join('\n')}\n`);

const missing = pages.filter(p => !existsSync(join(OUT, p.path === '/' ? 'index.html' : `${p.path.slice(1)}.html`)));
if (missing.length) throw new Error(`no page file for ${missing.map(p => p.path).join(', ')}`);

console.log(`${OUT}: ${moved} pages as <path>.html, _headers (${kept.length} rules)`);
