import { expect, test } from 'bun:test';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { marked } from 'marked';
import { descriptionOf, sectionDescriptionProblems } from '../tools/descriptions.ts';
import { markdownHeadings, pageMarkdown } from '../tools/markdown-headings.ts';

const siteDir = resolve(import.meta.dir, '..');
const fallback = 'The guide describes the behavior of apps on each platform.';
const derive = (markdown: string) => descriptionOf(marked.lexer(markdown), fallback);

function withHeadingSite(run: (dir: string, write: (path: string, content: string) => void) => void) {
  const root = mkdtempSync(join(siteDir, 'node_modules/.heading-test-'));
  const dir = join(root, 'docs/site');
  const write = (path: string, content: string) => {
    const file = join(dir, path);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  };
  try {
    for (const file of [
      '../constants/site.ts', '../markdown-fences.ts', '../tools/markdown-headings.ts', '../tools/markdown-check.ts',
      '../tools/gen.ts', '../tools/descriptions.ts', '../tools/prompts.ts',
      '../../../editors/vscode/syntaxes/exact-contract.tmLanguage.json',
    ]) {
      const dest = resolve(dir, 'tests', file);
      mkdirSync(dirname(dest), { recursive: true });
      copyFileSync(resolve(import.meta.dir, file), dest);
    }
    run(dir, write);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

