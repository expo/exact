test('the Markdown checker accepts a setext H2 and reports invalid heading outlines', () => withHeadingSite((dir, write) => {
  const origin = 'https://headings.example';
  const description = 'A guide for testing how the site checks headings.';
  const pages: [string, string, ((header: string) => string)?][] = [
    ['/valid', 'Setup\n-----\n\n### Detail\n\nSome text.'],
    ['/list', '## Setup\n\n<!-- cards -->\n\n- #### In a list\n  Some text.'],
    ['/callout', '## Setup\n\n> [!NOTE]\n> #### In a callout\n> Some text.'],
    ['/feedback', '### After malformed feedback', header => header.replace('# Guide\n\n', '# Guide\n')],
    ['/feedback-open', '### After feedback', header => header.replace('<AgentInstructions>\n\n', '<AgentInstructions>\nProse follows the tag.\n\n')],
    ['/feedback-close', '### After feedback', header => header.replace('\n\n</AgentInstructions>', '\n</AgentInstructions>')],
    ['/feedback-prose', '### After feedback', header => header.replace('</AgentInstructions>\n\n', '</AgentInstructions>\nProse follows the tag.\n\n')],
    ['/empty', '##\n\n### After an empty H2'],
  ];
  write('content/pages.json', JSON.stringify(pages.map(([path]) => ({ path, title: 'Guide', description }))));
  for (const [path, body, editHeader] of pages) {
    const header = `---
title: "Guide"
description: "${description}"
---

> ## Documentation index
> Fetch the complete documentation index at: ${origin}/llms.txt
> Use this file to discover all available pages before exploring further.

# Guide

<AgentInstructions>

## Submitting feedback

\`bun exact.mjs feedback status\` says when to keep a note. Under \`never\`, keep none.
\`bun exact.mjs feedback note "Exact docs: ${origin}${path}: feedback"\`

</AgentInstructions>

`;
    write(`dist${path}.md`, `${editHeader?.(header) ?? header}${body}\n`);
  }
  const links = pages.map(([path]) => `[Guide](${origin}${path}.md)`);
  write('dist/404.md', '# Page not found\n');
  write('dist/llms.txt', links.join('\n'));
  write('dist/sitemap.md', links.map(link => `${link} | Type: Guide`).join('\n'));
  const check = Bun.spawnSync([process.execPath, 'tools/markdown-check.ts', 'dist'], {
    cwd: dir, env: { ...process.env, SITE_ORIGIN: origin, FORCE_COLOR: '0', NO_COLOR: '1' },
  });
  expect(check.exitCode).toBe(1);
  expect(check.stderr.toString().trimEnd().split('\n')).toEqual([
    'markdown-check: 9 problems',
    '  /list.md: a level 4 heading below a level 2 heading: #### In a list',
    '  /callout.md: a level 4 heading below a level 2 heading: #### In a callout',
    '  /feedback.md: a level 3 heading below a level 1 heading: ### After malformed feedback',
    '  /feedback.md: no policy-aware feedback block naming this page below the H1',
    '  /feedback-open.md: a level 3 heading below a level 1 heading: ### After feedback',
    '  /feedback-close.md: a level 3 heading below a level 1 heading: ### After feedback',
    '  /feedback-prose.md: a level 3 heading below a level 1 heading: ### After feedback',
    '  /empty.md: an empty heading: ##',
    '  /empty.md: a level 3 heading below a level 1 heading: ### After an empty H2',
  ]);
}));

test('split-page Markdown keeps a first indented code block', () => {
  const tokens = marked.lexer('## A section\n\n    first()\n    second()\n\nThe next paragraph.\n');
  const markdown = pageMarkdown(tokens, raw => raw, 'A section');
  expect(markdown).toBe('# A section\n\n    first()\n    second()\n\nThe next paragraph.');
});

test('Markdown section boundaries include setext headings and skip fenced code', () => {
  const markdown = [
    'Recipe', '======', '', '   ````ts', '## Inside', '```', '## After a short marker',
    '~~~~', '## After a different marker', '```` trailing text', '## After trailing text',
    '  `````', '', '   ## C#', '', 'First section.', '', 'Setext heading', '--------------', '',
    'Second section.', '', '## Closing hashes ###', '',
  ].join('\n');
  expect(markdownHeadings(markdown).map(({ level, text, start, headingEnd, end }) => ({
    level, text, heading: markdown.slice(start, headingEnd).trimEnd(), section: markdown.slice(start, end).trimEnd(),
  }))).toEqual([
    { level: 1, text: 'Recipe', heading: 'Recipe\n======', section: markdown.trimEnd() },
    { level: 2, text: 'C#', heading: '   ## C#', section: '   ## C#\n\nFirst section.' },
    { level: 2, text: 'Setext heading', heading: 'Setext heading\n--------------', section: 'Setext heading\n--------------\n\nSecond section.' },
    { level: 2, text: 'Closing hashes', heading: '## Closing hashes ###', section: '## Closing hashes ###' },
  ]);
});

test('Sound lists its opening sentences when the next sentence starts with code', () => {
  const sound = [
    '- **A local speech recognizer may still need a language download.**',
    '  `speechRecognitionStatus.local` describes the engine, not its installed languages.',
    '- **An audio player is silent in iPhone Silent mode.** The default audio session is `ambient`.',
    '- **A scheduled sound plays after Stop.** A sequencer can schedule each step ahead.',
    '- **The first sound on the web is silent.** A sound a page plays on load is dropped.',
  ].join('\n');
  expect(derive(sound)).toBe('A local speech recognizer may still need a language download. An audio player is silent in iPhone Silent mode. A scheduled sound plays after Stop.');
});

test('a long sentence is cut at a word when its only earlier period ends e.g.', () => {
  const start = 'Load a configuration document from a local source, e.g. ';
  const sentence = `${start}${'a folder with data '.repeat(13).trim()}.`;
  const result = derive(sentence);
  expect(result.startsWith(`${start}a folder`)).toBe(true);
  expect(result.endsWith('…')).toBe(true);
  expect(result.length).toBeLessThanOrEqual(180);
});

