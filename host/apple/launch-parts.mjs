// Builds module launch parts and their services for an Apple build.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, resolve } from 'node:path';
import { launchModules } from '../../scripts/launch-modules.mjs';

export { launchModules };

/** Writes a generated SwiftPM target with each module's `apple/launch/*.swift`
 * and a registry of their `ExactLaunchPart` types, in `launch` order. SwiftPM
 * needs it inside the package. Returns its directory, or null if there are none. */
export function writeLaunchParts(pkg, app) {
  const modules = launchModules(app.dir, app.manifest);
  if (!modules.some(m => m.launch.length)) return null;
  const dir = resolve(pkg, '.launch-parts', app.id);
  mkdirSync(dir, { recursive: true });
  const keep = new Set(['Registry.swift']), types = [];
  const put = (name, text) => { const to = resolve(dir, name); if (!existsSync(to) || readFileSync(to, 'utf8') !== text) writeFileSync(to, text); };
  for (const m of modules) for (const f of m.launch) {
    const text = readFileSync(f, 'utf8'), name = `${m.name}-${basename(f)}`;
    for (const match of text.matchAll(/(?:struct|class|enum)\s+(\w+)\s*:[^{]*\bExactLaunchPart\b/g)) types.push(match[1]);
    keep.add(name);
    put(name, text);
  }
  put('Registry.swift', `// Generated by host/apple/build.mjs from app.json launch; never committed.\nimport ExactKit\n\npublic enum ExactLaunchParts {\n    public static let all: [ExactLaunchPart.Type] = [${types.map(t => `${t}.self`).join(', ')}]\n}\n`);
  for (const f of readdirSync(dir)) if (!keep.has(f)) rmSync(resolve(dir, f));
  return dir;
}

/** Each launch module's `apple/service/*.swift`, built as its own dylib.
 * ExactKit loads it when the launch part's policy says, never during launch. */
export const launchServices = (modules, buildDir) => modules.filter(m => m.service.length)
  .map(m => ({ name: m.name, load: `lib${m.name}_service.dylib`, framework: serviceFramework(m.name), built: resolve(buildDir, `lib${m.name}_service.dylib`), sources: m.service }));

/** swiftc's arguments for a service dylib, before its target. */
export const serviceArgs = svc => ['-parse-as-library', '-emit-library', '-O', '-swift-version', '5', '-module-name', `ExactService_${svc.name}`, ...svc.sources, '-lsqlite3', '-o', svc.built];

/** The objects SwiftPM compiled ExactLaunchParts into, in `binDir` (its --show-bin-path): Swift Build links the
 * target into one `ExactLaunchParts.o`; the native build system (what a Linux cross build runs) leaves one object
 * per source in `ExactLaunchParts.build/`. Empty when neither is there. */
export function launchPartsObjects(binDir) {
  const merged = resolve(binDir, 'ExactLaunchParts.o'), dir = resolve(binDir, 'ExactLaunchParts.build');
  if (existsSync(merged)) return [merged];
  return existsSync(dir) ? readdirSync(dir).filter(f => f.endsWith('.o')).sort().map(f => resolve(dir, f)) : [];
}

/** Throws unless the linked launch parts have at most 32 KiB of text and data
 * and no static initializer or ObjC +load, which would run outside the timed
 * `launch()` call, or if their objects are missing and cannot be audited.
 * `objects` is one object or the list launchPartsObjects returns; the budget is their sum. */
export function auditLaunchParts(objects, modules, read) {
  const list = typeof objects === 'string' ? [objects] : objects;
  if (!list.length || !list.every(existsSync)) {
    throw new Error(`host/apple: module launch parts (app.json launch) cannot be audited: ${list.length ? `${list.find(o => !existsSync(o))} is missing` : 'SwiftPM left no ExactLaunchParts object'}`);
  }
  const problems = [];
  let text = 0, data = 0, validSize = true, validCommands = true, sections = '';
  for (const object of list) {
    const size = read('xcrun', ['size', object]), commands = read('otool', ['-l', object]);
    const [, row] = (size.stdout ?? '').trim().split('\n');
    const [t, d] = (row ?? '').trim().split(/\s+/).map(Number);
    if (size.status === 0 && [t, d].every(n => Number.isSafeInteger(n) && n >= 0)) { text += t; data += d; } else validSize = false;
    if (commands.status !== 0 || !/\bcmd LC_SEGMENT(?:_64)?\b/.test(commands.stdout ?? '')) validCommands = false;
    sections += `${commands.stdout ?? ''}\n`;
  }
  if (!validSize) {
    problems.push('size inspection failed: xcrun size did not report nonnegative byte counts; check the Xcode toolchain and rebuild');
  }
  if (!validCommands) {
    problems.push('load-command inspection failed: otool did not report a Mach-O segment; check the Xcode toolchain and rebuild');
  }
  if (validSize && text + data > 32768) {
    problems.push(`${text + data} bytes of text and data, over the 32 KiB budget`);
  }
  if (/sectname (__mod_init_func|__init_offsets)/.test(sections)) {
    problems.push('a static initializer (it runs before launch, outside the timed call)');
  }
  if (/sectname __objc_nl(cls|cat)list/.test(sections)) {
    problems.push('an Objective-C +load');
  }
  if (problems.length) {
    throw new Error(`host/apple: module launch parts (app.json launch): ${problems.join('; ')}`);
  }
  console.log(`host/apple: launch parts ${modules.map(m => m.name).join(', ')}: ${text + data} B, no initializers`);
}

/** A launch service's framework in an archive, which takes no loose dylibs: `observe` is `ExactObserveService`. */
export function serviceFramework(name) {
  return `Exact${name.replace(/(^|[^A-Za-z0-9]+)([A-Za-z0-9])/g, (_, _sep, c) => c.toUpperCase())}Service`;
}
