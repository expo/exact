// @ref LLP 1133.023 D8, D9, D10 — the generated intents module: one Swift
// file per app from its faces, compiled to an object the executable links,
// and the App Intents metadata the system reads from the bundle.
//
// The generated code imports only AppIntents and Foundation. It reaches the
// host through `NotificationCenter`, the channel ExactKit and an app's
// modules already share in the process (ExactTools.swift): `exact.tools.call`
// for a call, `exact.contentIndex.query` for an entity query and
// `exact.contentIndex.open` for an entity's location. So it compiles beside
// the SwiftPM build, not inside it, and needs no ExactKit module to compile
// against.
import { dirname, resolve } from 'node:path';
import { existsSync, mkdirSync, rmSync, readFileSync, readdirSync, writeFileSync, cpSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { intentsMetadata as emittedIntentsMetadata } from './intents-metadata.mjs';
import { DOCUMENT_UTIS } from '../../scripts/app.mjs';
import { extensionModuleCache } from './extensions.mjs';
import { launchPartsObjects } from './launch-parts.mjs';

/** The protocols whose conformers' constant values the metadata pass reads (Xcode's list for App Intents). */
const gathered = ['AppIntent', 'EntityQuery', 'AppEntity', 'TransientEntity', 'AppEnum', 'AppShortcutProviding', 'AppShortcutsProvider',
  'AnyResolverProviding', 'AppIntentsPackage', 'DynamicOptionsProvider', 'OpenIntent', 'EntityStringQuery'];

/** The faces this platform compiles: `compat.inputs.faces` of the bake, each `{signature, face}` whose doors name `apple`. */
export const appleFaces = (compat) => (compat?.inputs?.faces ?? []).filter(f => (f.face?.doors ?? []).includes('apple'));

import { hasFileParameters } from './link.mjs';

// These table entries are not system-declared on every supported Apple host.
const undeclaredFileTypes = new Set(['net.daringfireball.markdown', 'org.xiph.ogg-audio']);
const fileUTI = mime => {
  const identifier = DOCUMENT_UTIS[mime];
  if (!identifier || identifier === 'public.folder' || undeclaredFileTypes.has(identifier))
    throw new Error(`host/apple: intents: ${mime} has no UTI declared on every supported Apple platform`);
  return identifier;
};

const typeName = (name) => name[0].toUpperCase() + name.slice(1);
const literal = (text) => JSON.stringify(String(text)).replace(/\\u([0-9a-f]{4})/g, (_, h) => `\\u{${h}}`);
const entityType = (kind) => `${typeName(kind)}Entity`;

/** A parameter's Swift type from its plan type and its face, or a reason it has none. */
function swiftType(planType, face) {
  const optional = /^option<(.*)>$/.exec(planType);
  const inner = optional ? optional[1] : planType;
  let type;
  if (face?.entity) type = inner === 'string' ? entityType(face.entity) : null;
  else if (inner === 'string' || inner.startsWith('enum<')) type = face?.type === 'file' ? 'IntentFile' : 'String';
  else if (inner === 'bool') type = 'Bool';
  else if (inner === 'number') type = face?.type === 'integer' ? 'Int' : 'Double';
  else type = null;
  if (!type) throw new Error(`host/apple: intents: a parameter of type ${planType} has no App Intents type (the compiler's intents-face-type should have refused it)`);
  return { type, optional: !!optional, entity: !!face?.entity };
}

/** A phrase's `${applicationName}` and `${<parameter>}` as App Shortcuts' interpolations. */
function phrase(text, parameters) {
  const parts = String(text).split(/(\$\{[A-Za-z_][A-Za-z0-9_]*\})/);
  return '"' + parts.map(part => {
    const name = /^\$\{(.*)\}$/.exec(part)?.[1];
    if (!name) return literal(part).slice(1, -1);
    if (name === 'applicationName') return '\\(.applicationName)';
    if (!parameters.includes(name)) throw new Error(`host/apple: intents: a phrase names \${${name}}, which is not a parameter`);
    return `\\(\\.$${name})`;
  }).join('') + '"';
}

const authentication = (word) => ({ local: '.requiresLocalDeviceAuthentication', always: '.alwaysAllowed' })[word] ?? '.requiresAuthentication';

/** The Swift of the app's intents module. */
export function intentsSource(faces, entities = {}) {
  const kinds = [...new Set(faces.flatMap(f => Object.values(f.face.parameters ?? {}).map(p => p.entity).filter(Boolean)))].sort();
  const out = [`// Generated by host/apple/intents.mjs from app.json's \`intents\` and the plan's tools (LLP 1133.023 D8). Not edited by hand.
import AppIntents
import Foundation${faces.some(f => Object.values(f.face.parameters ?? {}).some(p => p.type === 'file')) ? '\nimport UniformTypeIdentifiers' : ''}

/// The host's door and mirror, through the channel ExactKit observes (ExactTools.swift).
enum ExactDoor {
    struct Refusal: Error, CustomLocalizedStringResourceConvertible {
        let message: String
        var localizedStringResource: LocalizedStringResource { "\\(message)" }
    }

    /// Hands the host a call and awaits its answer (LLP 1111 D4's envelope). The system's cancellation of the
    /// intent's task is the caller's: the host drops a call still waiting and lets one that runs finish (LLP 1133.023 D7).
    @MainActor static func call(_ tool: String, _ args: [String: Any], digest: String) async throws -> [String: Any] {
        let body = NSMutableDictionary(dictionary: ["tool": tool, "args": args, "door": "apple", "digest": digest])
        let answer: [String: Any] = await withTaskCancellationHandler {
            await withCheckedContinuation { done in
                body["reply"] = { (answer: [String: Any]) in done.resume(returning: answer) }
                NotificationCenter.default.post(name: Notification.Name("exact.tools.call"), object: body)
                if body["taken"] as? Bool != true { done.resume(returning: ["outcome": "refused", "message": "This app has no tool door."]) }
            }
        } onCancel: {
            NotificationCenter.default.post(name: Notification.Name("exact.tools.cancel"), object: body)
        }
        guard answer["outcome"] as? String == "ok" else {
            let message = answer["message"] as? String ?? ""
            throw Refusal(message: message.isEmpty ? "\\(tool): \\(answer["outcome"] as? String ?? "failed")" : message)
        }
        return answer
    }

    /// The mirror's entries of \`kind\`: by id, matching a string, or all in the app's order.
    static func entries(_ kind: String, ids: [String]? = nil, matching: String? = nil) -> [[String: Any]] {
        let body = NSMutableDictionary(dictionary: ["kind": kind])
        if let ids { body["ids"] = ids }
        if let matching { body["matching"] = matching }
        NotificationCenter.default.post(name: Notification.Name("exact.contentIndex.query"), object: body)
        return body["entries"] as? [[String: Any]] ?? []
    }

    /// Opens an entry's location, as a search result's continuation does.
    @MainActor static func open(_ url: String) {
        NotificationCenter.default.post(name: Notification.Name("exact.contentIndex.open"), object: NSMutableDictionary(dictionary: ["url": url]))
    }
}
`];
  for (const kind of kinds) {
    const T = entityType(kind), title = entities[kind]?.title ?? typeName(kind);
    out.push(`
struct ${T}: AppEntity {
    static let typeDisplayRepresentation: TypeDisplayRepresentation = ${literal(title)}
    static let defaultQuery = ${T}Query()
    let id: String
    let title: String
    let subtitle: String?
    let url: String
    var displayRepresentation: DisplayRepresentation {
        DisplayRepresentation(title: "\\(title)", subtitle: subtitle.map { "\\($0)" })
    }
    init?(_ entry: [String: Any]) {
        guard let id = entry["id"] as? String, let title = entry["title"] as? String else { return nil }
        self.id = id; self.title = title
        subtitle = entry["description"] as? String
        url = entry["url"] as? String ?? "/"
    }
}

struct ${T}Query: EntityStringQuery {
    func entities(for identifiers: [${T}.ID]) async throws -> [${T}] {
        ExactDoor.entries(${literal(kind)}, ids: identifiers).compactMap(${T}.init)
    }
    func entities(matching string: String) async throws -> [${T}] {
        ExactDoor.entries(${literal(kind)}, matching: string).compactMap(${T}.init)
    }
    func suggestedEntities() async throws -> [${T}] {
        ExactDoor.entries(${literal(kind)}).compactMap(${T}.init)
    }
}

struct Open${T}: OpenIntent {
    static let title: LocalizedStringResource = ${literal(`Open ${title}`)}
    @Parameter(title: ${literal(title)}) var target: ${T}
    @MainActor func perform() async throws -> some IntentResult {
        ExactDoor.open(target.url)
        return .result()
    }
}
`);
  }
  for (const { signature, face } of faces) {
    const T = typeName(signature.name);
    const params = signature.parameters.map(([name, planType]) => ({ name, ...swiftType(planType, face.parameters?.[name]), title: face.parameters?.[name]?.title ?? name,
      description: face.parameters?.[name]?.description, accept: face.parameters?.[name]?.accept?.map(fileUTI) }));
    const fields = params.map(p => `    @Parameter(title: ${literal(p.title)}${p.description ? `, description: ${literal(p.description)}` : ''}${p.type === 'IntentFile' ? `, supportedContentTypes: [${p.accept.map(m => `UTType(importedAs: ${literal(m)})`).join(', ')}]` : ''}) var ${p.name}: ${p.type}${p.optional ? '?' : ''}`).join('\n');
    const names = new Set(params.map(p => p.name));
    for (const p of params.filter(p => p.type === 'IntentFile')) {
      let name = `${p.name}Path`;
      while (names.has(name)) name += '_';
      names.add(name); p.imported = name;
    }
    const value = (p) => p.type === 'IntentFile' ? p.imported : p.entity ? `self.${p.name}${p.optional ? '?' : ''}.id` : `self.${p.name}`;
    const args = params.length ? `[${params.map(p => `${literal(p.name)}: ${p.optional ? `${value(p)} as Any? ?? NSNull()` : value(p)}`).join(', ')}]` : '[:]';
    out.push(`
struct ${T}: AppIntent {
    static let title: LocalizedStringResource = ${literal(face.title ?? signature.name)}
    static let description = IntentDescription(${literal(signature.description)})
    static let authenticationPolicy: IntentAuthenticationPolicy = ${authentication(face.apple?.authentication)}
${fields}
    @MainActor func perform() async throws -> some IntentResult {
${signature.consequence === 'destroys' ? '        try await requestConfirmation()\n' : ''}${params.filter(p => p.type === 'IntentFile').map(p => `        let ${p.imported} = try await ExactDoor.IntentFiles.importFile(self.${p.name}, accept: [${p.accept.map(literal).join(', ')}])\n`).join('')}        _ = try await ExactDoor.call(${literal(signature.name)}, ${args}, digest: ${literal(face.digest ?? '')})
        return .result()
    }
}
`);
  }
  const phrased = faces.filter(f => f.face.apple?.phrases?.length);
  if (phrased.length) {
    out.push(`
struct ExactAppShortcuts: AppShortcutsProvider {
    static var appShortcuts: [AppShortcut] {
${phrased.map(({ signature, face }) => `        AppShortcut(intent: ${typeName(signature.name)}(), phrases: [${face.apple.phrases.map(p => phrase(p, signature.parameters.map(([n]) => n))).join(', ')}], shortTitle: ${literal(face.title ?? signature.name)}, systemImageName: ${literal(face.apple.systemImage ?? 'app')})`).join('\n')}
    }
}
`);
  }
  // What ExactKit calls by name, since it cannot name the generated types: an Objective-C class is kept by the link.
  out.push(`
@objc(ExactIntentsHooks) final class ExactIntentsHooks: NSObject {
    /// The index changed: App Shortcuts whose phrases name a parameter learn its values (D9).
    @objc static func parametersChanged() {
        ${phrased.length ? 'ExactAppShortcuts.updateAppShortcutParameters()' : '// no App Shortcuts'}
    }
}
`);
  if (faces.some(f => Object.values(f.face.parameters ?? {}).some(p => p.type === 'file'))) out.push(readFileSync(new URL('./Sources/ExactKit/IntentFiles.swift', import.meta.url), 'utf8').replace('enum IntentFiles {', 'extension ExactDoor {\nenum IntentFiles {') + '\n}\n');
  return out.join('');
}

/** The manifest's `shortcuts` as the bundle declares them (D3): iOS's Home Screen quick actions, each carrying its
 * location, and the Mac's Dock menu, which ExactShortcuts reads; none on tvOS, which has neither. */
export function shortcutKeys(app, platform) {
  const items = app.manifest.shortcuts ?? [];
  if (!items.length || platform === 'tvos') return {};
  if (platform === 'macos') return { ExactShortcutItems: items.map(({ name, url }) => ({ name, url })) };
  return { UIApplicationShortcutItems: items.map(item => ({ UIApplicationShortcutItemType: item.url, UIApplicationShortcutItemTitle: item.name,
    ...(item.description ? { UIApplicationShortcutItemSubtitle: item.description } : {}),
    ...(item.apple?.symbol ? { UIApplicationShortcutItemIconSymbolName: item.apple.symbol } : {}),
    UIApplicationShortcutItemUserInfo: { url: item.url } })) };
}

/** The compiler flags that write the constant values the metadata pass reads, into `values`. */
export const constValueArgs = (values, dir) => {
  writeFileSync(resolve(dir, 'protocols.json'), JSON.stringify(gathered));
  return ['-emit-const-values-path', values, '-Xfrontend', '-const-gather-protocols-file', '-Xfrontend', resolve(dir, 'protocols.json')];
};

const xcrunFind = tool => spawnSync('xcrun', ['--find', tool], { encoding: 'utf8' });

/** Xcode's App Intents metadata pass over a compiled module: writes `dir/Metadata.appintents`, which the bundle
 * that holds the binary carries in its resources, or throws. The processor is the one of the Xcode that compiled
 * the module, found as `swiftc` is (`xcrun` honours `DEVELOPER_DIR` and `xcode-select`); its toolchain is the
 * directory that holds its `usr/bin`. */
export function intentsMetadata({ moduleName, dir, sdk, triple, platform, deployment, binary, sources, values, dependencies = [], runApple, find = xcrunFind }) {
  const metadata = resolve(dir, 'Metadata.appintents');
  // Linux has no Xcode and no processor: the portable emitter writes the same file from the module's constant values.
  if (process.platform === 'linux') {
    const major = parseInt(JSON.parse(readFileSync(resolve(sdk, 'SDKSettings.json'), 'utf8')).Version);
    const actions = emittedIntentsMetadata(JSON.parse(readFileSync(values, 'utf8')), major, { module: moduleName });
    mergeIntentsMetadata(actions, dependencies.map(f => JSON.parse(readFileSync(f, 'utf8'))));
    mkdirSync(metadata, { recursive: true });
    writeFileSync(resolve(metadata, 'extract.actionsdata'), JSON.stringify(actions));
    writeFileSync(resolve(metadata, 'version.json'), JSON.stringify({ toolsVersion: 'exact-1', version: '3.0' }));
    return metadata;
  }
  const found = find('appintentsmetadataprocessor'), processor = found.status === 0 ? found.stdout.trim() : '';
  if (!processor) throw new Error(`host/apple: intents: xcrun finds no appintentsmetadataprocessor: ${(found.stderr ?? found.error?.message ?? '').trim()}`);
  const toolchain = resolve(processor, '../../..');
  writeFileSync(resolve(dir, 'sources.txt'), sources.join('\n') + '\n');
  writeFileSync(resolve(dir, 'values.txt'), values + '\n');
  writeFileSync(resolve(dir, 'none.txt'), '');
  writeFileSync(resolve(dir, 'dependencies.txt'), dependencies.join('\n') + '\n');
  const xcode = /Build version (\S+)/.exec(spawnSync('xcodebuild', ['-version'], { encoding: 'utf8' }).stdout ?? '')?.[1] ?? '';
  runApple(processor, ['--toolchain-dir', toolchain, '--module-name', moduleName, '--sdk-root', sdk,
    '--xcode-version', xcode, '--platform-family', platform === 'macos' ? 'macOS' : platform === 'watchos' ? 'watchOS' : 'iOS', '--deployment-target', deployment, '--target-triple', triple,
    '--output', dir, '--binary-file', binary, '--source-file-list', resolve(dir, 'sources.txt'), '--swift-const-vals-list', resolve(dir, 'values.txt'),
    '--metadata-file-list', resolve(dir, 'none.txt'), '--static-metadata-file-list', resolve(dir, 'dependencies.txt'),
    '--compile-time-extraction', '--deployment-aware-processing', '--no-app-shortcuts-localization'], { stdio: 'ignore' });
  if (!existsSync(resolve(metadata, 'extract.actionsdata'))) throw new Error(`host/apple: intents: the metadata pass wrote no ${metadata}/extract.actionsdata`);
  return metadata;
}

/** Combine the metadata of the images an app ships. */
export function mergeIntentsMetadata(actions, dependencies) {
  for (const other of dependencies) {
    if (other.autoShortcutProviderMangledName) {
      if (actions.autoShortcutProviderMangledName) throw new Error('host/apple: intents: more than one shortcuts provider');
      actions.autoShortcutProviderMangledName = other.autoShortcutProviderMangledName;
    }
    for (const [key, value] of Object.entries(other)) {
      if (Array.isArray(value)) actions[key].push(...value);
      else if (value && typeof value === 'object' && key !== 'generator') {
        for (const [name, entry] of Object.entries(value)) {
          if (name in actions[key]) throw new Error(`host/apple: intents: duplicate ${key} identifier ${name}`);
          actions[key][name] = entry;
        }
      }
    }
  }
  return actions;
}

/** The floor of what the generated code uses: App Shortcuts' short titles and symbols are iOS 17 and macOS 14 (D17). */
const floor = { ios: 17, macos: 14 };

/**
 * Compile the app's intents module for `triple` and extract its metadata. Answers `{ object, digest, place(bundleResources) }`,
 * or null with no Apple faces or native intents. Cached by generated source, native constants, deployment and compiler.
 */
export function buildIntents({ app, compat, directory, sdkName, sdk, triple, platform, deployment, swiftc, runApple, nativeModules = [] }) {
  const faces = appleFaces(compat);
  nativeModules = nativeModules.filter(Boolean);
  if (!faces.length && !nativeModules.length) return null;
  if (faces.length && parseFloat(deployment) < floor[platform]) throw new Error(`host/apple: intents: a faced tool needs ${platform === 'ios' ? 'iOS' : 'macOS'} ${floor[platform]} or later, and app.json's host.${platform}.minimumOS is ${deployment}`);
  const fileFloor = { ios: 18, macos: 15 };
  if (hasFileParameters(app.manifest.intents) && parseFloat(deployment) < fileFloor[platform]) throw new Error(`host/apple: intents: a file parameter with supportedContentTypes needs host.${platform}.minimumOS ${fileFloor[platform]}.0 or later`);
  const source = intentsSource(faces, app.manifest.intents?.entities ?? {});
  const emitter = process.platform === 'linux' ? Buffer.concat([readFileSync(new URL('./intents-metadata.mjs', import.meta.url)), readFileSync(new URL(import.meta.url))]) : '';
  const digest = createHash('sha256').update(JSON.stringify([source, swiftc, triple, sdk, deployment, nativeModules.map(m => [m.moduleName, readFileSync(m.values, 'utf8'), createHash('sha256').update(readFileSync(m.binary)).digest('hex')])])).update(emitter).digest('hex').slice(0, 16);
  const dir = resolve(directory, digest), object = resolve(dir, 'ExactIntents.o'), metadata = resolve(dir, 'Metadata.appintents');
  if (!existsSync(resolve(metadata, 'extract.actionsdata'))) {
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(dir, { recursive: true });
    const file = resolve(dir, 'ExactIntents.swift'), values = resolve(dir, 'ExactIntents.swiftconstvalues');
    writeFileSync(file, source);
    const started = Date.now();
    runApple('xcrun', ['--sdk', sdkName, 'swiftc', '-parse-as-library', '-wmo', '-O', '-swift-version', '5', '-module-name', 'ExactIntents',
      '-module-cache-path', extensionModuleCache, '-target', triple, '-sdk', sdk,
      ...constValueArgs(values, dir),
      '-c', file, '-o', object]);
    const dependencies = nativeModules.map(m => {
      const nativeDir = resolve(dir, m.moduleName); mkdirSync(nativeDir, { recursive: true });
      return resolve(intentsMetadata({ ...m, dir: nativeDir, sdk, triple, platform, deployment, runApple }), 'extract.actionsdata');
    });
    intentsMetadata({ moduleName: 'ExactIntents', dir, sdk, triple, platform, deployment, binary: object, sources: [file], values, dependencies, runApple });
    console.log(`host/apple: intents: ${faces.length} faced tool${faces.length === 1 ? '' : 's'} compiled with their metadata (${Date.now() - started} ms)`);
  }
  return {
    object, digest, tools: faces.map(f => f.signature.name),
    // A native intent must be mapped before App Intents resolves its type, including on a headless launch.
    launchLink: nativeModules.flatMap(m => m.moduleName === 'ExactAppModules'
      ? ['-Xlinker', '-needed_library', '-Xlinker', m.binary, '-Xlinker', '-rpath', '-Xlinker', platform === 'ios' ? '@executable_path/Frameworks' : '@executable_path']
      : JSON.parse(readFileSync(m.values, 'utf8')).flatMap(t => ['-Xlinker', '-u', '-Xlinker', `_exact_launch_intent_type_${t.mangledTypeName}`])),
    /** Into the bundle's resources (the bundle's root on iOS, Contents/Resources on the Mac), before it is signed. */
    place(resources) { rmSync(resolve(resources, 'Metadata.appintents'), { recursive: true, force: true }); cpSync(metadata, resolve(resources, 'Metadata.appintents'), { recursive: true }); },
  };
}


/** Gather constants under the shipping module's name and compiler context.
 * The binary, compiler and arguments identify the cached constants. */
export function nativeIntentModule({ moduleName, binary, sources, args, directory, swiftc, runApple }) {
  const binaries = [binary].flat();
  const hash = createHash('sha256').update(JSON.stringify([swiftc, args, gathered, sources.map(f => readFileSync(f, 'utf8'))]));
  for (const file of binaries) hash.update(readFileSync(file));
  const digest = hash.digest('hex').slice(0, 16);
  const dir = resolve(directory, digest), values = resolve(dir, `${moduleName}.swiftconstvalues`);
  binary = binaries.length === 1 ? binaries[0] : resolve(dir, `${moduleName}.o`);
  if (!existsSync(values) || !existsSync(binary)) {
    mkdirSync(dir, { recursive: true });
    // A typecheck or object compile refuses object inputs, such as a native package's ExactPackage.o that the link takes.
    const object = a => /\.[oa]$/.test(a ?? '');
    const checking = args.filter((a, i) => a !== '-emit-library' && a !== '-o' && args[i - 1] !== '-o' && !object(a)
      && !(a === '-Xlinker' && object(args[i + 1])));
    // The native build system can leave per-source objects. The extractor takes one binary, so compile a
    // whole-module object in that layout.
    try {
      const constants = constValueArgs(values, dir);
      runApple('xcrun', [...checking, '-wmo', ...(binaries.length > 1 ? ['-c', '-o', binary] : ['-typecheck']), ...constants]);
    }
    catch (error) { rmSync(dir, { recursive: true, force: true }); throw error; }
  }
  const constants = JSON.parse(readFileSync(values, 'utf8'));
  return constants.length ? { moduleName, binary, sources, values } : null;
}


/** Swift Build and the native build system place their Swift modules and C module maps differently. */
export function launchIntentModule({ pkg, binDir, sourceDirectory, sdkName, sdk, triple, framework, conditions, ...options }) {
  const sources = readdirSync(sourceDirectory).filter(f => f.endsWith('.swift')).sort().map(f => resolve(sourceDirectory, f));
  const moduleMap = [resolve(binDir, 'CExactLaunch.build/module.modulemap'),
    resolve(binDir, '../../Intermediates.noindex', `GeneratedModuleMaps${sdkName === 'macosx' ? '' : `-${sdkName}`}`, 'CExactLaunch.modulemap')].find(existsSync);
  if (!moduleMap) throw new Error(`host/apple: intents: no CExactLaunch module map beside ${binDir}`);
  const objects = launchPartsObjects(binDir);
  if (!objects.length) throw new Error(`host/apple: intents: no ExactLaunchParts objects beside ${binDir}`);
  const module = nativeIntentModule({ ...options, binary: objects, moduleName: 'ExactLaunchParts', sources,
    args: ['--sdk', sdkName, 'swiftc', '-parse-as-library', '-swift-version', '5', '-module-name', 'ExactLaunchParts', ...conditions.flatMap(c => ['-D', c]),
      '-target', triple, '-sdk', sdk, '-I', binDir, '-I', resolve(binDir, 'Modules'), '-I', resolve(pkg, 'Sources/CExact'),
      '-Xcc', `-fmodule-map-file=${resolve(pkg, 'Sources/CExact/module.modulemap')}`,
      '-Xcc', `-fmodule-map-file=${moduleMap}`, ...(framework ? ['-F', dirname(framework), '-I', resolve(framework, 'Modules')] : []), ...sources] });
  // SwiftPM localizes internal Swift symbols in its merged object. Public C getters remain linker roots,
  // reference each type's metadata, and need never run. Keep them beside the declarations to reach fileprivate types.
  const constants = module ? JSON.parse(readFileSync(module.values, 'utf8')) : [];
  for (const file of sources) {
    const marker = '\n// Generated native intent roots.\n', source = readFileSync(file, 'utf8');
    const roots = constants.filter(t => t.file === file).map(t => {
      const symbol = `exact_launch_intent_type_${t.mangledTypeName}`, type = t.typeName.slice('ExactLaunchParts.'.length);
      const available = (t.availabilityAttributes ?? []).filter(a => a.introducedVersion).map(a => `@available(${a.platform} ${a.introducedVersion}, *)\n`).join('');
      return `${available}@_cdecl("${symbol}") public func ${symbol}() -> UnsafeRawPointer {\n    unsafeBitCast(${type}.self as Any.Type, to: UnsafeRawPointer.self)\n}\n`;
    }).join('');
    const next = source.split(marker)[0] + (roots ? marker + roots : '');
    if (next !== source) writeFileSync(file, next);
  }
  return module;
}
